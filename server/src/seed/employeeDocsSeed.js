import mongoose from 'mongoose';
import { AppraisalLetter } from '../models/AppraisalLetter.js';
import { Form16 } from '../models/Form16.js';
import { currentFyStart, fyLabel } from '../models/employeeDocOptions.js';
import { encryptBuffer, sha256 } from '../utils/fileCrypto.js';
import { simplePdf } from '../utils/simplePdf.js';

/** Demo Performance Appraisal Letters and Form 16 Part A/B for one employee (clearly marked as samples). */
export async function seedEmployeeDocs({ employee, by }) {
  const code = String(employee.employeeCode).replace(/[^A-Za-z0-9_-]/g, '');
  const file = (aad, lines) => {
    const buf = simplePdf([...lines, '', 'SAMPLE DOCUMENT - generated by the seed script for demonstration only.']);
    return { size: buf.length, checksum: sha256(buf), ...encryptBuffer(buf, aad) };
  };

  if (!(await AppraisalLetter.exists({ employee: employee._id }))) {
    const thisYear = new Date().getFullYear();
    const letters = [
      { year: thisYear, month: 4, appraisalType: 'annual', title: `Annual Performance Appraisal ${thisYear - 1}-${String(thisYear % 100).padStart(2, '0')}`, rating: 'exceeds', effectiveDate: new Date(`${thisYear}-04-01`) },
      { year: thisYear - 1, month: 10, appraisalType: 'mid_year', title: `Mid-Year Review ${thisYear - 1}`, rating: 'meets' },
      { year: thisYear - 1, month: 4, appraisalType: 'annual', title: `Annual Performance Appraisal ${thisYear - 2}-${String((thisYear - 1) % 100).padStart(2, '0')}`, rating: 'meets', effectiveDate: new Date(`${thisYear - 1}-04-01`) },
    ];
    const months = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];
    await AppraisalLetter.insertMany(letters.map((l) => {
      const _id = new mongoose.Types.ObjectId();
      return {
        _id, employee: employee._id, ...l, remarks: 'Demo letter',
        fileName: `Appraisal_Letter_${code}_${months[l.month - 1]}_${l.year}${l.appraisalType !== 'annual' ? `_${l.appraisalType}` : ''}.pdf`,
        originalName: 'appraisal-letter.pdf',
        ...file(`appraisal-letter:${_id}`, ['Performance Appraisal Letter', `Employee: ${employee.name} (${employee.employeeCode})`, l.title, `Period: ${months[l.month - 1]} ${l.year}`]),
        uploadedBy: by._id, updatedBy: by._id,
      };
    }));
  }

  if (!(await Form16.exists({ employee: employee._id }))) {
    const fy = currentFyStart() - 1; // last completed financial year
    await Form16.insertMany(['A', 'B'].map((part) => {
      const _id = new mongoose.Types.ObjectId();
      return {
        _id, employee: employee._id, part, fyStart: fy,
        certificateNo: part === 'A' ? 'DEMOCERT01' : '', employerTan: 'DEMO00000D', issueDate: new Date(`${fy + 1}-06-10`),
        fileName: `Form16_Part${part}_${code}_FY${fyLabel(fy)}.pdf`, originalName: `form16-part-${part.toLowerCase()}.pdf`,
        ...file(`form16:${_id}`, [`Form 16 - Part ${part}`, `Employee: ${employee.name} (${employee.employeeCode})`, `Financial year ${fyLabel(fy)} / Assessment year ${fyLabel(fy + 1)}`]),
        uploadedBy: by._id, updatedBy: by._id,
      };
    }));
  }
}
